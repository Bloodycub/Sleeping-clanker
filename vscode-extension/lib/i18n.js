let current = 'en';

/**
 * The language to use: the setting when it names one of LANGUAGES, else (auto, empty or unknown)
 * VS Code's display language (`ru`, `fi-FI`, `en-us`…) when it is one of them, else English.
 * @param {unknown} setting @param {unknown} [vscodeLanguage]
 */
function resolve(setting, vscodeLanguage) {
  const s = String(setting || AUTO).trim().toLowerCase();
  if (LANGUAGES.includes(s)) return s;
  const v = String(vscodeLanguage || '').trim().toLowerCase().split(/[-_]/)[0];
  return LANGUAGES.includes(v) ? v : 'en';
}

/** @param {string} lang one of LANGUAGES (anything else = English) @returns {string} the language now in use */
function setLanguage(lang) {
  current = LANGUAGES.includes(lang) ? lang : 'en';
  return current;
}

/** The language in use. */
function language() {
  return current;
}

/**
 * The text in the language in use; `{n}` is replaced by args[n] (once, so an argument that contains
 * `{0}` is never expanded again).
 * @param {string} text the English text (the key) @param {...unknown} args
 */
function t(text, ...args) {
  const d = DICT[current];
  const s = d && Object.prototype.hasOwnProperty.call(d, text) ? d[text] : text;
  if (!args.length) return s;
  return s.replace(/\{(\d+)\}/g, (m, i) => (Number(i) < args.length ? String(args[Number(i)]) : m));
}

/** The dictionary of the language in use, for the webview; null for English (no translation needed). */
function strings() {
  return DICT[current] || null;
}

module.exports = { AUTO, LANGUAGES, NAMES, DICT, resolve, setLanguage, language, t, strings };
